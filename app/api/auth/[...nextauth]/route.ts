// ============================================================================
// Auth.js を Next.js の API ルートとして公開するファイル（自分で書く）
// 外部のサービスやスマホアプリから呼ばれるAPIが必要なときは、route.ts でAPIエンドポイントを作ります
// ----------------------------------------------------------------------------
// フォルダ名 `[...nextauth]` は「キャッチオールルート」というNext.jsの機能で、
// `/api/auth/` 以下のどんなパス（`/api/auth/signin`、`/api/auth/callback/google`
// など）へのリクエストも、このファイル1つで受け止められるようにする仕組み。
// フォルダ名自体がAuth.jsの規約で決まっているので、変更しないこと。
//
// やることは非常にシンプルで、ルートの auth.ts で作った `handlers` を
// そのままGET/POSTとしてexportするだけ。
// ============================================================================

// ----------------------------------------------------------------------------
// 最初に必要なimport
// ----------------------------------------------------------------------------
// handlers: auth.ts で `export const { handlers, ... } = NextAuth({...})`
//           として作った、GET/POST両方の処理が入ったオブジェクト
//
import { handlers } from "@/auth";

// ----------------------------------------------------------------------------
// GET と POST をexportする
// ----------------------------------------------------------------------------
// Next.jsのApp Routerでは、route.tsファイルの中で `GET`、`POST` という名前で
// exportした関数が、それぞれのHTTPメソッドのリクエストを処理する関数として
// 自動的に認識される（これもNext.js自体の規約）。
// handlers オブジェクトには既に GET と POST が入っているので、
// 分割代入でそのまま名前を付けてexportすればよい。
//
export const { GET, POST } = handlers;

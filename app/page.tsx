// ここでは「Googleログインが動くかどうか」を確認するためだけの、仮のボタンを
// 置く。本格的な画面デザインは後で作るので、まずは最小限の動作確認が目的。
//
// 使う仕組み: Server Action
//   App Routerでは、関数の中に "use server" と書くだけで、その関数が
//   「ブラウザからではなく、サーバー側で実行される処理」になる。
//   <form action={その関数}> という形で紐付けると、フォームが送信された
//   タイミングでサーバー側の関数が実行される（JavaScriptをブラウザに
//   ほとんど送らずにボタンの処理が書けるのがNext.js App Routerの特徴）。
// ============================================================================

// ----------------------------------------------------------------------------
// 最初に必要なimport
// ----------------------------------------------------------------------------
// signIn: auth.ts で `export const { ..., signIn, ... } = NextAuth({...})`
//         として作った、ログイン処理を開始するための関数
//
import { signIn } from "@/auth";

// ----------------------------------------------------------------------------
// TODO: ログインボタンを置く
// ----------------------------------------------------------------------------

export default function Home() {
    return (
        <form action={async () => {
            'use server';
            await signIn("google");
        }}>
            <button type="submit">Googleアカウントでログイン</button>
        </form>
    )
}

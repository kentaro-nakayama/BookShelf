// ----------------------------------------------------------------------------
// loading.tsx という名前のファイルを置くと、Next.jsがそのフォルダ配下の
// ページを読み込んでいる間、自動的にこの中身を代わりに表示してくれる
// （内部的にはページをReactのSuspenseで包んでくれている）。
//
// このファイルは app/ の直下にあるので、アプリの全ページが対象になる。
// 特定の画面だけ別の見た目にしたい場合は、そのフォルダに loading.tsx を
// 追加すれば、近いほうが優先される。
//
// 表示されるのはヘッダーより下の領域だけで、ヘッダーと下部タブバーは
// 出たまま操作できる（レイアウトは読み込み直されないため）。
// 読み込み中でも他のタブに移動できるので、待たされている感じが減る。
//
// このアプリのページはすべてDBや外部APIを待つ動的なページなので、
// 画面を移動したときに必ずこの表示が挟まる。
// ============================================================================


// ============================================================================
// 初期データ(シードデータ)を投入するスクリプト（自分で書く）
// ----------------------------------------------------------------------------
// 直接実行して使う想定（`npx tsx db/seed.ts` のような形。package.jsonに
// `db:seed` スクリプトとして登録しておくと `npm run db:seed` で呼べて便利）。
//
// 今回は「ジャンル」が固定マスタ(ユーザーが自由に追加できない一覧)という設計なので、
// 新しいジャンルを増やしたくなったら、この配列に追記してから再実行する運用になる。
// 対象データ: docs/requirements.md / docs/database-design.md で確定したジャンル一覧
//   1: 小説, 2: ビジネス, 3: 自己啓発, 4: 技術書, 5: エッセイ, 6: その他
// ============================================================================

// ----------------------------------------------------------------------------
// 最初に必要なimport
// ----------------------------------------------------------------------------
// db:     db/index.ts で作ったDBクライアント
import { db } from "./index";
//
// genres: db/schema.ts で定義した genres テーブル（挿入先）
import { genres } from "./schema";

// ----------------------------------------------------------------------------
// TODO 1: 挿入するデータの配列を用意する
// ----------------------------------------------------------------------------
// genres テーブルの id は自動採番(smallint、手動で番号を振る設計)だったので、
// ここで { id: 1, name: "小説" } のような形のオブジェクトを6件、配列にする。
//
const initialGenres = [
    { id: 1, name: "小説" },
    { id: 2, name: "ビジネス" },
    { id: 3, name: "自己啓発" },
    { id: 4, name: "技術書" },
    { id: 5, name: "エッセイ" },
    { id: 6, name: "その他" },
];

// ----------------------------------------------------------------------------
// TODO 2: 実際に挿入する処理を書く
// ----------------------------------------------------------------------------
// db.insert(テーブル).values(配列) という書き方で複数行まとめて挿入できる。
//
// このスクリプトを誤って2回実行してしまっても安全にしたい（同じidを再挿入すると
// 本来ならUNIQUE制約違反でエラーになる）ので、末尾に .onConflictDoNothing() を
// つけると「もう同じidが入っていたら何もしない（エラーにしない）」という
// 動きになる。
//
// DBへの操作は非同期(Promiseを返す)なので、async function を定義して
// その中で await する形にするのが書きやすい。
//
// async function main() {
//   await db.insert(genres).values(initialGenres).onConflictDoNothing();
//   console.log(`seeded ${initialGenres.length} genres`);
// }
//
// main() を呼び出すのを忘れずに（関数を定義しただけでは実行されない）。
// スクリプトの最後に実行結果に応じて process.exit(0) / process.exit(1) を
// 呼ぶと、ターミナルから見たときに成功/失敗が分かりやすい。
//
// シード処理を定義
async function main() {
    await db.insert(genres).values(initialGenres).onConflictDoNothing();
    console.log(`seeded ${initialGenres.length} genres`);
}
// シード処理を実行
main()
    .then(() => process.exit(0))
    .catch((err) => {
        console.error(err);
        process.exit(1);
    }); 


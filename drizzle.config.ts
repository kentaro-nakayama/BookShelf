// ----------------------------------------------------------------------------
// drizzle-kit（db/schema.ts からマイグレーションSQLを生成・実行するCLIツール）に
// 「スキーマはどこ？」「生成したSQLはどこに出す？」「どのDBに繋ぐ？」を教えるための設定。
// アプリ本体ではなく、ターミナルから `npx drizzle-kit <コマンド>` を実行したときだけ読まれる。
// ============================================================================

// ----------------------------------------------------------------------------
// 最初に必要なimport
// ----------------------------------------------------------------------------
// defineConfig: 設定オブジェクトを作るための関数（型補完が効くようにするためのヘルパー）
//
import { defineConfig } from "drizzle-kit";

// ----------------------------------------------------------------------------
// 基本形
// ----------------------------------------------------------------------------
// export default defineConfig({
//   項目名: 値,
//   ...
// });

// ----------------------------------------------------------------------------
// TODO: 必要な設定項目
// ----------------------------------------------------------------------------
// - schema:  スキーマファイルの場所 → "./db/schema.ts"
//
// - out:     生成されたマイグレーションSQLの出力先フォルダ
//            → 自由に決められるが、慣習的に "./drizzle"
//
// - dialect: 使うDBの種類 → "postgresql"
//
// - dbCredentials.url: 接続文字列
//            マイグレーション実行時は「プールされていない直接接続」を使うのが推奨
//           （プールされた接続だとマイグレーションが失敗することがあるため）。
//            .env に入っている DATABASE_URL_UNPOOLED を使う
//           （DATABASE_URL ではない点に注意。こちらはアプリの通常クエリ用）。
//            process.env.DATABASE_URL_UNPOOLED のように読み取る。
const databaseUrl = process.env.DATABASE_URL_UNPOOLED; 

if (!databaseUrl) {
    throw new Error("DATABASE_URL_UNPOOLEDが設定されていません. 環境変数ファイルを確認してください.");
}

export default defineConfig({
    schema: "./db/schema.ts",
    out: "./drizzle",
    dialect: "postgresql",
    dbCredentials: {
        url: databaseUrl,
    },
});
